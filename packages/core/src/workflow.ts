import type { Client, Tool, ToolRunner, TurnCallbacks } from "./engine.ts";
import { runTurn } from "./engine.ts";
import type { Message, Result, ViseError } from "./errors.ts";
import {
  checkToolAvailability,
  runProfileStep,
  type WorkflowProfiles,
} from "./workflow-profiles.ts";

export type WorkflowStep =
  | { type: "instruction"; text: string }
  /** Switch to this profile from here on (its instructions and tool list), as `/profile <name>` does. */
  | { type: "profile"; name: string }
  | {
      type: "tool";
      name: string;
      args: Record<string, unknown>;
      /**
       * Arguments are binding: plain values are passed as written and only
       * `{ "$model": hint }` arguments are generated by the model (a step with
       * none is called directly). Without it, `args` is a template and the
       * model generates every argument.
       */
      exact?: boolean;
    };

/** Put the workflow's input where a step's text says `{{input}}` (an empty string when it ran with none). */
const withInput = (text: string, input: string): string =>
  text.replaceAll("{{input}}", input);

/** The model-provided argument marker: its value is a hint for the model. */
const modelHint = (value: unknown): string | undefined => {
  if (typeof value !== "object" || value === null) return undefined;
  const hint = (value as Record<string, unknown>)["$model"];
  return typeof hint === "string" ? hint : undefined;
};

export interface Workflow {
  steps: WorkflowStep[];
}

export type WorkflowScope = "project" | "global";

/**
 * What a frontend is told while a workflow runs. `step` is 1-based and `total`
 * counts the closing "final response" as a step, so the last `step` is
 * `index === total`. `end` always follows `start` (also on failure or stop):
 * `step` is the one that was running, `error` is why it stopped (absent on success).
 */
export type WorkflowEvent =
  | { kind: "start"; name: string; total: number }
  | { kind: "step"; name: string; index: number; total: number; label: string }
  | { kind: "end"; name: string; step: number; total: number; error?: ViseError }
  /** A workflow that stopped early left the session in `name` (the profile it switched to) instead of `was`, the one you had. */
  | { kind: "profile"; name: string | undefined; was: string | undefined };

/** A short name for a step, for the progress display. */
export function stepLabel(step: WorkflowStep): string {
  if (step.type === "profile") return `profile ${step.name}`;
  if (step.type === "tool") return `tool ${step.name}`;
  const first = step.text.split("\n").find((line) => line.trim() !== "") ?? "";
  const text = first.replace(/^#+\s*/, "").trim();
  return text.length > 60 ? `${text.slice(0, 59)}…` : text;
}

interface WorkflowRunOptions {
  client: Client;
  tools: ToolRunner;
  toolDefs: Tool[];
  messages: Message[];
  name: string;
  workflow: Workflow;
  request: string;
  callbacks: TurnCallbacks;
  /** Switching profiles; when given, the tool steps are checked against the profiles before anything runs. */
  profiles?: WorkflowProfiles;
  /** Told when the run starts, before each step, and how it ended. */
  onWorkflow?: (event: WorkflowEvent) => void;
}

/** Execute workflow steps in order, then ask the model for a final response. */
export async function runWorkflow(
  options: WorkflowRunOptions,
): Promise<Result<string>> {
  const { name, workflow, onWorkflow } = options;
  const total = workflow.steps.length + 1;
  const progress = { step: 0 };
  const result = await runSteps(options, total, progress);
  onWorkflow?.({
    kind: "end",
    name,
    step: progress.step,
    total,
    ...(result.ok ? {} : { error: result.error }),
  });
  return result;
}

async function runSteps(
  options: WorkflowRunOptions,
  total: number,
  progress: { step: number },
): Promise<Result<string>> {
  const { messages, name, workflow, request, onWorkflow } = options;
  if (options.profiles) {
    const checked = await checkToolAvailability(workflow, options.profiles);
    if (!checked.ok) return checked;
  }
  messages.push({
    role: "user",
    content: `Run workflow '${name}'. User request: ${request || "(none)"}`,
  });
  onWorkflow?.({ kind: "start", name, total });

  for (const [index, step] of workflow.steps.entries()) {
    progress.step = index + 1;
    onWorkflow?.({
      kind: "step",
      name,
      index: index + 1,
      total,
      label: stepLabel(step),
    });
    if (step.type === "instruction") {
      const result = await runInstructionStep(
        options,
        index + 1,
        withInput(step.text, request),
      );
      if (!result.ok) return result;
      continue;
    }

    const result =
      step.type === "profile"
        ? await runProfileStep(options.profiles, step.name)
        : await runToolStep(options, index + 1, step);
    if (!result.ok) return result;
    if (step.type === "profile")
      onWorkflow?.({ kind: "profile", name: step.name, was: undefined });
  }

  progress.step = total;
  onWorkflow?.({ kind: "step", name, index: total, total, label: "final response" });
  messages.push({
    role: "user",
    content: `All steps in workflow '${name}' are complete. Respond to the user's request: ${request || "(none)"}`,
  });
  return runTurn(
    options.client,
    options.tools,
    messages,
    options.toolDefs,
    workflowCallbacks(options),
  );
}

async function runInstructionStep(
  options: WorkflowRunOptions,
  number: number,
  text: string,
): Promise<Result<string>> {
  options.messages.push({
    role: "user",
    content: `Workflow instruction step ${number}:\n${text}`,
  });
  return runTurn(
    options.client,
    options.tools,
    options.messages,
    options.toolDefs,
    workflowCallbacks(options),
  );
}

type ToolStep = Extract<WorkflowStep, { type: "tool" }>;

/** The arguments for a tool step: generated by the model, fixed, or a mix (`exact`). */
async function toolArguments(
  options: WorkflowRunOptions,
  number: number,
  step: ToolStep,
  toolSchema: Record<string, unknown>,
): Promise<Result<Record<string, unknown>>> {
  const entries = Object.entries(step.args);
  if (!step.exact) {
    const schema = withRequiredPlaceholders(toolSchema, Object.keys(step.args));
    return generateArguments(
      options,
      number,
      step.name,
      `Argument template: ${JSON.stringify(step.args)}`,
      schema,
    );
  }
  const fixed = Object.fromEntries(
    entries
      .filter(([, value]) => modelHint(value) === undefined)
      .map(([key, value]) => [
        key,
        typeof value === "string" ? withInput(value, options.request) : value,
      ]),
  );
  const hints = entries.filter(([, value]) => modelHint(value) !== undefined);
  if (hints.length === 0) return validated(fixed, step.name, toolSchema);
  const properties = toolSchema.properties as Record<string, unknown>;
  const schema = {
    ...toolSchema,
    properties: Object.fromEntries(hints.map(([key]) => [key, properties[key]])),
    required: hints.map(([key]) => key),
  };
  const lines = hints.map(([key, value]) => {
    const hint = modelHint(value);
    return hint ? `- ${key}: ${hint}` : `- ${key}`;
  });
  const generated = await generateArguments(
    options,
    number,
    step.name,
    `These arguments are fixed and already set: ${JSON.stringify(fixed)}\nSupply only these arguments:\n${lines.join("\n")}`,
    schema,
  );
  if (!generated.ok) return generated;
  return validated({ ...generated.value, ...fixed }, step.name, toolSchema);
}

/** Check finished arguments against the tool's own schema. */
function validated(
  args: Record<string, unknown>,
  toolName: string,
  schema: Record<string, unknown>,
): Result<Record<string, unknown>> {
  const problem = validateArguments(args, schema);
  if (!problem) return { ok: true, value: args };
  return {
    ok: false,
    error: {
      kind: "malformed",
      body: `workflow generated invalid arguments for '${toolName}': ${problem}`,
    },
  };
}

/** Ask the model for a JSON object matching `schema`, keeping the exchange in the conversation. */
async function generateArguments(
  options: WorkflowRunOptions,
  number: number,
  toolName: string,
  guide: string,
  schema: Record<string, unknown>,
): Promise<Result<Record<string, unknown>>> {
  options.messages.push({
    role: "user",
    content: [
      `Workflow tool step ${number}: generate arguments for '${toolName}'.`,
      `User request: ${options.request || "(none)"}`,
      guide,
      "Use prior workflow messages and outputs when deciding argument values. Return only a JSON object matching this schema:",
      JSON.stringify(schema),
    ].join("\n"),
  });
  const generated = await (
    options.client.as?.("workflow") ?? options.client
  ).chat(
    options.messages,
    // The tool list keeps the request encoded as the conversation's own turns are,
    // so it shares their prompt prefix (and the server's cache) instead of re-reading it.
    options.toolDefs,
    undefined,
    options.callbacks.onThinking,
    undefined,
    { type: "object", ...schema },
    options.callbacks.abort,
  );
  if (!generated.ok) return generated;
  const args = parseAndValidateArguments(
    generated.value.content,
    toolName,
    schema,
  );
  if (args.ok) {
    options.messages.push({ role: "assistant", content: generated.value.content });
  }
  return args;
}

async function runToolStep(
  options: WorkflowRunOptions,
  number: number,
  step: Extract<WorkflowStep, { type: "tool" }>,
): Promise<Result<void>> {
  const tool = options.toolDefs.find(
    (definition) => definition.function.name === step.name,
  );
  if (!tool) {
    return {
      ok: false,
      error: {
        kind: "malformed",
        body: `workflow references unknown tool '${step.name}'`,
      },
    };
  }
  const properties = tool.function.parameters.properties;
  if (
    typeof properties !== "object" ||
    properties === null ||
    Array.isArray(properties)
  ) {
    return {
      ok: false,
      error: {
        kind: "malformed",
        body: `tool '${step.name}' has no object argument schema`,
      },
    };
  }
  const unsupported = Object.keys(step.args).find(
    (key) => !(key in properties),
  );
  if (unsupported) {
    return {
      ok: false,
      error: {
        kind: "malformed",
        body: `workflow argument template for '${step.name}' contains unknown argument '${unsupported}'`,
      },
    };
  }
  const args = await toolArguments(options, number, step, tool.function.parameters);
  if (!args.ok) return args;

  options.callbacks.onToolCall?.(step.name, 0, args.value);
  let output: string;
  try {
    output = await options.tools.run(
      step.name,
      args.value,
      options.callbacks.abort,
    );
  } catch (error) {
    output = `error: ${error instanceof Error ? error.message : String(error)}`;
  }
  options.callbacks.onToolResult?.(step.name, 0, output);
  // A picture the step produced is shown, and travels with its result (never left for the next tool).
  const images = options.tools.takeImages?.() ?? [];
  for (const image of images) options.callbacks.onImage?.(image);
  options.messages.push({
    role: "user",
    content: `Workflow tool step ${number} result from '${step.name}':\n${output}`,
    ...(images.length > 0 ? { images } : {}),
  });
  if (output.trimStart().startsWith("error:")) {
    return {
      ok: false,
      error: {
        kind: "malformed",
        body: `workflow tool '${step.name}' failed: ${output}`,
      },
    };
  }
  return { ok: true, value: undefined };
}

function parseAndValidateArguments(
  content: string,
  toolName: string,
  schema: Record<string, unknown>,
): Result<Record<string, unknown>> {
  const args = parseArguments(content, toolName);
  if (!args.ok) return args;
  const validationError = validateArguments(args.value, schema);
  if (validationError) {
    return {
      ok: false,
      error: {
        kind: "malformed",
        body: `workflow generated invalid arguments for '${toolName}': ${validationError}`,
      },
    };
  }
  return args;
}

function parseArguments(
  content: string,
  toolName: string,
): Result<Record<string, unknown>> {
  try {
    const parsed: unknown = JSON.parse(content);
    if (
      typeof parsed !== "object" ||
      parsed === null ||
      Array.isArray(parsed)
    ) {
      throw new Error("expected an object");
    }
    return { ok: true, value: parsed as Record<string, unknown> };
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    return {
      ok: false,
      error: {
        kind: "malformed",
        body: `workflow could not generate arguments for '${toolName}': ${reason}`,
      },
    };
  }
}

function withRequiredPlaceholders(
  source: Record<string, unknown>,
  placeholders: string[],
): Record<string, unknown> {
  const schema = { ...source };
  const required = Array.isArray(schema.required)
    ? schema.required.filter(
        (entry): entry is string => typeof entry === "string",
      )
    : [];
  schema.required = [...new Set([...required, ...placeholders])];
  return schema;
}

function workflowCallbacks(options: WorkflowRunOptions): TurnCallbacks {
  return options.callbacks;
}

function validateArguments(
  args: Record<string, unknown>,
  schema: Record<string, unknown>,
): string | undefined {
  const properties = schema.properties;
  if (
    typeof properties !== "object" ||
    properties === null ||
    Array.isArray(properties)
  ) {
    return "tool schema properties must be an object";
  }
  const propertySchemas = properties as Record<string, unknown>;
  const required = Array.isArray(schema.required)
    ? schema.required.filter(
        (entry): entry is string => typeof entry === "string",
      )
    : [];
  for (const key of required) {
    if (!(key in args)) return `missing required argument '${key}'`;
  }
  for (const [key, value] of Object.entries(args)) {
    if (!(key in propertySchemas)) return `unknown argument '${key}'`;
    const definition = propertySchemas[key];
    if (
      typeof definition !== "object" ||
      definition === null ||
      Array.isArray(definition)
    ) {
      return `invalid schema for argument '${key}'`;
    }
    const error = validateValue(
      value,
      definition as Record<string, unknown>,
      key,
    );
    if (error) return error;
  }
  return undefined;
}

function validateValue(
  value: unknown,
  schema: Record<string, unknown>,
  path: string,
): string | undefined {
  const type = schema.type;
  const valid =
    type === "string"
      ? typeof value === "string"
      : type === "integer"
        ? typeof value === "number" && Number.isInteger(value)
        : type === "number"
          ? typeof value === "number" && Number.isFinite(value)
          : type === "boolean"
            ? typeof value === "boolean"
            : type === "array"
              ? Array.isArray(value)
              : type === "object"
                ? typeof value === "object" &&
                  value !== null &&
                  !Array.isArray(value)
                : true;
  if (!valid) return `argument '${path}' must be ${String(type)}`;
  if (Array.isArray(schema.enum) && !schema.enum.includes(value)) {
    return `argument '${path}' must be one of the allowed values`;
  }
  if (
    type === "array" &&
    Array.isArray(value) &&
    typeof schema.items === "object" &&
    schema.items !== null
  ) {
    const itemSchema = schema.items as Record<string, unknown>;
    for (const [index, item] of value.entries()) {
      const error = validateValue(item, itemSchema, `${path}[${index}]`);
      if (error) return error;
    }
  }
  if (
    type === "object" &&
    typeof value === "object" &&
    value !== null &&
    !Array.isArray(value)
  ) {
    const nested = schema.properties;
    if (
      typeof nested === "object" &&
      nested !== null &&
      !Array.isArray(nested)
    ) {
      return validateArguments(value as Record<string, unknown>, {
        properties: nested,
        required: schema.required,
      });
    }
  }
  return undefined;
}
