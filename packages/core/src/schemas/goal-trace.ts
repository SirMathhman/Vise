import { z } from "zod";
import type { GoalTraceEntry, ExitReason } from "../goal-trace.ts";

const exitReasonSchema: z.ZodType<ExitReason> = z.enum([
  "goal-off",
  "no-goal",
  "met",
  "blocked",
  "unknown",
  "same-step",
  "max-continues-declined",
  "halted-progress",
  "turn-failed",
  "interrupted",
  "exception",
]) as z.ZodType<ExitReason>;

export const goalTraceFactSchema: z.ZodType<GoalTraceEntry> = z.discriminatedUnion("kind", [
  z.object({
    kind: z.literal("setting"),
    enabled: z.boolean(),
    at: z.string(),
    after: z.number(),
  }),
  z.object({
    kind: z.literal("turn_start"),
    line: z.string(),
    enabled: z.boolean(),
    goal: z.string().optional(),
    at: z.string(),
    after: z.number(),
  }),
  z.object({
    kind: z.literal("ask"),
    purpose: z.string(),
    attempt: z.number(),
    question: z.string(),
    reply: z.string().optional(),
    failure: z.string().optional(),
    at: z.string(),
    after: z.number(),
  }),
  z.object({
    kind: z.literal("goal"),
    goal: z.string(),
    doneWhen: z.string(),
    hold: z.string().optional(),
    previous: z.string().optional(),
    fallback: z.boolean(),
    at: z.string(),
    after: z.number(),
  }),
  z.object({
    kind: z.literal("verdict"),
    verdict: z.string(),
    detail: z.string(),
    at: z.string(),
    after: z.number(),
  }),
  z.object({
    kind: z.literal("progress"),
    progress: z.string(),
    detail: z.string(),
    keepGoing: z.boolean().optional(),
    at: z.string(),
    after: z.number(),
  }),
  z.object({
    kind: z.literal("continue"),
    note: z.string(),
    continues: z.number(),
    repeats: z.number(),
    toolsRan: z.boolean(),
    at: z.string(),
    after: z.number(),
  }),
  z.object({
    kind: z.literal("exit"),
    reason: exitReasonSchema,
    detail: z.string().optional(),
    lastReply: z.string(),
    toolResults: z.number(),
    at: z.string(),
    after: z.number(),
  }),
]) as z.ZodType<GoalTraceEntry>;
