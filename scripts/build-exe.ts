// Builds build/exe/vise.exe, a Windows program that opens Vise in a WebView2 window. Four steps:
// the page's script is bundled, an entry file is written that embeds the page's files (a compiled program
// cannot read them from disk) and runs Vise, the entry is compiled to build/exe/vise-server.exe, and the
// launcher (exe/launcher, Rust with wry) is built with that server embedded in it.

import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { buildAssets } from "../src/web/server/page.ts";

// Every path below is relative to the repository root, so the script works from any directory.
process.chdir(join(import.meta.dir, ".."));
const out = "build/exe";
await mkdir(out, { recursive: true });

const assets = await buildAssets();
if (!assets.ok) {
  console.error(assets.error.message);
  process.exit(1);
}
await Bun.write(join(out, "client.js"), assets.value.script);

// The entry is generated, not checked by tsc: its imports are text files, which the type checker cannot type.
await Bun.write(
  join(out, "server-entry.ts"),
  [
    "// Generated by scripts/build-exe.ts. The page's files are embedded as text and passed to main.",
    'import shell from "../../src/web/client/shell.html" with { type: "text" };',
    'import style from "../../src/web/client/style.css" with { type: "text" };',
    'import script from "./client.js" with { type: "text" };',
    'import { main } from "../../index.ts";',
    "",
    "await main({ html: shell, script, style });",
    "",
  ].join("\n"),
);

const steps: string[][] = [
  ["bun", "build", "--compile", join(out, "server-entry.ts"), "--outfile", join(out, "vise-server.exe")],
  ["cargo", "build", "--release", "--manifest-path", "exe/launcher/Cargo.toml", "--target-dir", join(out, "target")],
];
for (const step of steps) {
  const proc = Bun.spawn(step, { stdout: "inherit", stderr: "inherit" });
  if ((await proc.exited) !== 0) {
    console.error(`build:exe: the step failed: ${step.join(" ")}`);
    process.exit(1);
  }
}

await Bun.write(join(out, "vise.exe"), Bun.file(join(out, "target", "release", "vise.exe")));
console.log(`built ${join(out, "vise.exe")}`);
